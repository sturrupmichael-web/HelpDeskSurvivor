// Builds the published index.html: one self-contained page with the CSS and all the
// game's JavaScript inlined. Ad blockers (e.g. uBlock Origin) block some script URLs
// by name, which breaks a game made of many module files; an inline script has no URL.
// Edit the code under src/, play it with dev.html, then run `npm run build`.
//
// `node build.mjs --preview` builds a test copy into preview/ instead (served at
// /preview/ next to the live game): same game, version ending in -pre, a PREVIEW banner
// on the title screen, and hidden from search engines. See README "Previews".

import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync, rmSync, cpSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { LEADERBOARD } from './data/leaderboard.js';

// Version = time of the last commit in UTC, e.g. 2026.10.20-2131 (see src/version.js), so
// the same code always gets the same version, however often it's rebuilt. Falls back to
// the build time when git isn't available.
const PREVIEW = process.argv.includes('--preview');
const VERSION =
  commitTime().toISOString().replace(/^(\d+)-(\d+)-(\d+)T(\d+):(\d+).*/, '$1.$2.$3-$4$5') + (PREVIEW ? '-pre' : '');
const js = await build({
  entryPoints: ['src/main.js'],
  bundle: true,
  format: 'esm',
  target: 'es2022',
  minify: true,
  write: false,
  define: { __VERSION__: JSON.stringify(VERSION), __PREVIEW__: JSON.stringify(PREVIEW) },
});
const css = readFileSync('src/ui/style.css', 'utf8');
const html = readFileSync('dev.html', 'utf8')
  .replace('<link rel="stylesheet" href="src/ui/style.css">', () => `<style>\n${css}</style>`)
  .replace('<script type="module" src="src/main.js"></script>', () =>
    `<script type="module">\n${js.outputFiles[0].text.replaceAll('</script', '<\\/script')}</script>`,
  )
  .replace('<title>', '<!-- Generated by build.mjs from dev.html and src/. Do not edit by hand. -->\n  <title>');
if (PREVIEW) {
  // The page plus every file it loads, so the preview doesn't depend on the live files.
  rmSync('preview', { recursive: true, force: true });
  mkdirSync('preview');
  for (const f of ['sprites/out', 'icons', 'manifest.webmanifest', 'sw.js', 'privacy.html', 'terms.html']) {
    cpSync(f, `preview/${f}`, { recursive: true });
  }
  const manifest = JSON.parse(readFileSync('manifest.webmanifest', 'utf8'));
  writeFileSync('preview/manifest.webmanifest', JSON.stringify({ ...manifest, name: 'Helpdesk Survivors PREVIEW', short_name: 'HDS Preview' }, null, 2) + '\n');
  writeFileSync('preview/index.html', withCsp(html.replace('<meta charset="utf-8">', '<meta charset="utf-8">\n  <meta name="robots" content="noindex">')));
  console.log(`preview/index.html: ${(html.length / 1024).toFixed(0)} KB, version ${VERSION}`);
} else {
  writeFileSync('index.html', withCsp(html));
  // dev.html keeps the same policy; its hash list is refreshed here when its inline script changes.
  writeFileSync('dev.html', withCsp(readFileSync('dev.html', 'utf8')));
  console.log(`index.html: ${(html.length / 1024).toFixed(0)} KB, version ${VERSION}`);
}

// Content Security Policy: the page may only run its own scripts (the inline ones are
// allowed by hash, so an injected <script> won't run) and only talk to this site and
// the leaderboard. Same policy, with the script files allowed, goes in dev.html.
function withCsp(page) {
  const hashes = [...page.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/g)].map(
    (m) => `'sha256-${createHash('sha256').update(m[1]).digest('base64')}'`,
  );
  const csp = [
    "default-src 'self'",
    `script-src 'self' ${hashes.join(' ')}`,
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data: blob:",
    `connect-src 'self' ${new URL(LEADERBOARD.url).origin}`,
    "worker-src 'self'",
    "manifest-src 'self'",
    "object-src 'none'",
    "base-uri 'none'",
    "form-action 'none'",
  ].join('; ');
  return page.replace(/<meta http-equiv="Content-Security-Policy"[^>]*>\n\s*/, '').replace(
    '<meta charset="utf-8">',
    `<meta charset="utf-8">\n  <meta http-equiv="Content-Security-Policy" content="${csp}">`,
  );
}

function commitTime() {
  try {
    return new Date(Number(execFileSync('git', ['log', '-1', '--format=%ct'], { encoding: 'utf8' }).trim()) * 1000);
  } catch {
    return new Date();
  }
}
